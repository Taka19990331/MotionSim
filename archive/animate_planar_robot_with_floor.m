function animate_planar_robot_with_floor(t, q, dq, param)
%ANIMATE_PLANAR_ROBOT_WITH_FLOOR
% Animate planar robot with floor contact at:
%   1. Second joint
%   2. End effector

    %% Input check

    if size(q, 2) ~= 2
        error('q must have two columns.');
    end

    if size(dq, 2) ~= 2
        error('dq must have two columns.');
    end

    if length(t) ~= size(q, 1) || length(t) ~= size(dq, 1)
        error('t, q, and dq must have matching sample counts.');
    end

    %% Playback settings

    playback_speed = 1.0;
    frame_rate = 30;

    animation_time = ...
        t(1):(playback_speed / frame_rate):t(end);

    animation_indices = interp1( ...
        t, ...
        1:length(t), ...
        animation_time, ...
        'nearest');

    animation_indices = unique(animation_indices);

    %% Preallocate

    number_of_samples = length(t);

    joint_position = zeros(number_of_samples, 2);
    ee_position = zeros(number_of_samples, 2);

    joint_contact_force = zeros(number_of_samples, 2);
    ee_contact_force = zeros(number_of_samples, 2);

    %% Calculate positions and contact forces

    for k = 1:number_of_samples

        q_k = q(k, :).';
        dq_k = dq(k, :).';

        q1 = q_k(1);
        q2 = q_k(2);

        joint_position(k, :) = [
            param.l1 * cos(q1), ...
            param.l1 * sin(q1)
        ];

        ee_position(k, :) = ...
            joint_position(k, :) ...
            + [
                param.l2 * cos(q2), ...
                param.l2 * sin(q2)
            ];

        [F_contact_k, ~] = ...
            surface_contact_force( ...
                q_k, ...
                dq_k, ...
                param);

        joint_contact_force(k, :) = ...
            F_contact_k.joint.';

        ee_contact_force(k, :) = ...
            F_contact_k.ee.';

    end

    %% Figure settings

    total_length = ...
        param.l1 + param.l2;

    axis_limit = ...
        1.1 * total_length;

    figure;

    hold on;
    grid on;
    axis equal;

    xlim([-axis_limit, axis_limit]);

    ylim([ ...
        min(-axis_limit, param.z_floor - 0.1), ...
        axis_limit]);

    xlabel('X [m]');
    ylabel('Z [m]');

    title('Planar robot with surface contact');

    %% Floor

    plot( ...
        [-axis_limit, axis_limit], ...
        [param.z_floor, param.z_floor], ...
        '-', ...
        'LineWidth', 3);

    %% Initial frame

    k0 = animation_indices(1);

    p_joint = joint_position(k0, :);
    p_ee = ee_position(k0, :);

    link1_plot = plot( ...
        [0, p_joint(1)], ...
        [0, p_joint(2)], ...
        '-', ...
        'LineWidth', 4);

    link2_plot = plot( ...
        [p_joint(1), p_ee(1)], ...
        [p_joint(2), p_ee(2)], ...
        '-', ...
        'LineWidth', 4);

    plot( ...
        0, ...
        0, ...
        'o', ...
        'MarkerSize', 9, ...
        'MarkerFaceColor', 'auto');

    joint_plot = plot( ...
        p_joint(1), ...
        p_joint(2), ...
        'o', ...
        'MarkerSize', 9, ...
        'MarkerFaceColor', 'auto');

    ee_plot = plot( ...
        p_ee(1), ...
        p_ee(2), ...
        'o', ...
        'MarkerSize', 9, ...
        'MarkerFaceColor', 'auto');

    trajectory_plot = plot( ...
        p_ee(1), ...
        p_ee(2), ...
        '--', ...
        'LineWidth', 1);

    joint_force_plot = quiver( ...
        p_joint(1), ...
        p_joint(2), ...
        0, ...
        0, ...
        0, ...
        'LineWidth', 2);

    ee_force_plot = quiver( ...
        p_ee(1), ...
        p_ee(2), ...
        0, ...
        0, ...
        0, ...
        'LineWidth', 2);

    time_text = text( ...
        -0.95 * axis_limit, ...
         0.90 * axis_limit, ...
        sprintf('t = %.2f s', t(k0)));

    %% Animation loop

    force_scale = 0.01;

    for frame = 1:length(animation_indices)

        k = animation_indices(frame);

        p_joint = joint_position(k, :);
        p_ee = ee_position(k, :);

        set(link1_plot, ...
            'XData', [0, p_joint(1)], ...
            'YData', [0, p_joint(2)]);

        set(link2_plot, ...
            'XData', [p_joint(1), p_ee(1)], ...
            'YData', [p_joint(2), p_ee(2)]);

        set(joint_plot, ...
            'XData', p_joint(1), ...
            'YData', p_joint(2));

        set(ee_plot, ...
            'XData', p_ee(1), ...
            'YData', p_ee(2));

        set(trajectory_plot, ...
            'XData', ee_position(1:k, 1), ...
            'YData', ee_position(1:k, 2));

        set(joint_force_plot, ...
            'XData', p_joint(1), ...
            'YData', p_joint(2), ...
            'UData', 0, ...
            'VData', ...
                force_scale ...
                * joint_contact_force(k, 2));

        set(ee_force_plot, ...
            'XData', p_ee(1), ...
            'YData', p_ee(2), ...
            'UData', 0, ...
            'VData', ...
                force_scale ...
                * ee_contact_force(k, 2));

        set(time_text, ...
            'String', ...
            sprintf( ...
                't = %.2f s, F_{joint} = %.1f N, F_{ee} = %.1f N', ...
                t(k), ...
                joint_contact_force(k, 2), ...
                ee_contact_force(k, 2)));

        drawnow;

    end

end